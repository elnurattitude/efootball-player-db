-- eFOOT MARKET: marketplace table + public policies
-- Run this script in Supabase Dashboard > SQL Editor.
create table if not exists public.account_listings (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 5 and 90),
  price_uzs bigint not null check (price_uzs > 0),
  description text not null default '',
  telegram_username text not null check (telegram_username ~ '^[A-Za-z0-9_]{5,32}$'),
  photo_url text,
  player_ids jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending','approved','rejected','sold')),
  created_at timestamptz not null default now()
);
create index if not exists account_listings_status_created_idx
  on public.account_listings (status, created_at desc);
create index if not exists account_listings_price_idx
  on public.account_listings (price_uzs);
alter table public.account_listings enable row level security;
grant select, insert on public.account_listings to anon, authenticated;
grant usage, select on sequence public.account_listings_id_seq to anon, authenticated;
drop policy if exists "Anyone can read approved listings" on public.account_listings;
create policy "Anyone can read approved listings"
  on public.account_listings for select
  to anon, authenticated using (status = 'approved');
drop policy if exists "Anyone can submit pending listings" on public.account_listings;
create policy "Anyone can submit pending listings"
  on public.account_listings for insert
  to anon, authenticated with check (status = 'pending');
-- Admin approval is performed from Supabase Dashboard > Table Editor.
-- Do not add a public UPDATE policy: it would let visitors approve their own listings.
